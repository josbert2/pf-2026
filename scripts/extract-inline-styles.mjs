// Turns the inline styles of a Framer export (section-grab capture) into a
// stylesheet keyed by Framer's hashed classes, so a JSX conversion that
// dropped inline styles (font vars, opacity, transforms…) renders like the
// original without hand-editing the JSX.
//
// usage: node scripts/extract-inline-styles.mjs <capture/index.html> <out.css>
import fs from "node:fs";
import { parseDocument, DomUtils } from "htmlparser2";

const [, , input, output] = process.argv;
if (!input || !output) {
  console.error("usage: node scripts/extract-inline-styles.mjs <index.html> <out.css>");
  process.exit(1);
}

const SKIP = new Set(["will-change", "corner-shape"]);
const HASH = /^framer-[A-Za-z0-9]{5,8}$/;

const doc = parseDocument(fs.readFileSync(input, "utf8"), { decodeEntities: true });
const isEl = (n) => n.type === "tag" || n.type === "script" || n.type === "style";

// Most specific selector for an element: its own hashed classes, or the
// nearest ancestor with one plus an nth-child path down to it.
function selectorFor(el) {
  const path = [];
  let cur = el;
  while (cur && isEl(cur)) {
    const own = (cur.attribs.class || "").split(/\s+/).filter((c) => HASH.test(c));
    if (own.length) {
      const base = own.map((c) => "." + c).join("");
      return path.length ? `${base} > ${path.reverse().join(" > ")}` : base;
    }
    const parent = cur.parent;
    if (!parent || !isEl(parent)) return null;
    const idx = parent.children.filter(isEl).indexOf(cur) + 1;
    path.push(`:nth-child(${idx})`);
    cur = parent;
  }
  return null;
}

const rules = new Map();
for (const el of DomUtils.findAll((n) => Boolean(n.attribs?.style), doc.children)) {
  const sel = selectorFor(el);
  if (!sel) continue;
  const decls = el.attribs.style
    .split(";")
    .map((d) => d.trim())
    .filter(Boolean)
    .map((d) => {
      const i = d.indexOf(":");
      return [d.slice(0, i).trim(), d.slice(i + 1).trim()];
    })
    .filter(([k, v]) => k && v && !SKIP.has(k))
    // relative asset URLs from the capture won't resolve from the stylesheet
    .filter(([, v]) => !/url\(/.test(v));
  if (!decls.length) continue;
  // A hashed class can be shared by several elements (e.g. the three nav
  // links). Keep only the declarations they all agree on; conflicting ones
  // are left to the element's own inline style / Framer's stylesheet.
  const prev = rules.get(sel);
  if (!prev) {
    rules.set(sel, new Map(decls));
    continue;
  }
  const next = new Map(decls);
  for (const [k, v] of prev) if (next.get(k) !== v) prev.set(k, null);
}

for (const [sel, decls] of rules) {
  const kept = [...decls].filter(([, v]) => v !== null);
  if (kept.length) rules.set(sel, kept);
  else rules.delete(sel);
}

let css = `/* Generated by scripts/extract-inline-styles.mjs from ${input.split("/").slice(-3).join("/")} — do not edit by hand. */\n`;
for (const [sel, decls] of rules) {
  css += `${sel} {${decls.map(([k, v]) => ` ${k}: ${v} !important;`).join("")} }\n`;
}
fs.writeFileSync(output, css);
console.log(`${rules.size} rules -> ${output}`);
